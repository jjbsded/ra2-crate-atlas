"""Reproduce standing-voxel pages using the verified original YR arithmetic.

Runs only pure math functions in a disposable 32-bit process. Never starts the
game, enters its main function, or accesses a live game process. No game binary
or machine code is embedded in the generated application module.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import textwrap
import zlib

ROOT = Path(__file__).resolve().parent
# Original YR 1.001 laboratory image (campaign speed patch, math unchanged).
GAME_SHA256 = '58144dbadf8a5ce7fa834b81498a41607a0405365c832171545494ae71321397'
COUNTS = (16, 36, 64, 245)


def module(record):
    rows = {(r['mode'], r['face']): r['pages'] for r in record['rows']}
    assert len(rows) == len(record['rows']) == 128
    for mode, count in enumerate(COUNTS, 1):
        for face in range(32):
            row = rows[mode, face]
            assert len(row) == count and all(isinstance(v, int) and 0 <= v < 32 for v in row)
    raw = b''.join(bytes(rows[mode, face]) for mode in range(1, 5) for face in range(32))
    encoded = '\n'.join('    '+repr(line) for line in textwrap.wrap(base64.b85encode(zlib.compress(raw, 9)).decode(), 88, break_on_hyphens=False))
    return f'''"""Native YR 1.001 standing-voxel VPL pages, modes 1..4, bridge facings 0..31.

Generated by generate-voxel-light-tables.py; do not edit the payload.
Game SHA256: {GAME_SHA256}
Raw pages SHA256: {hashlib.sha256(raw).hexdigest()}
See docs/vehicle-brightness-native.md for coordinate conventions and limits.
Only numerical outputs are included; no original executable code.
"""
import base64
import zlib

_COUNTS = {COUNTS!r}
_RAW = zlib.decompress(base64.b85decode(
{encoded}
))
assert len(_RAW) == 32 * sum(_COUNTS)
NATIVE_PAGES = {{}}
_offset = 0
for _mode, _count in enumerate(_COUNTS, 1):
    NATIVE_PAGES[_mode] = tuple(_RAW[_offset + i*_count:_offset + (i+1)*_count] for i in range(32))
    _offset += 32 * _count
del _RAW, _offset, _mode, _count
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game', required=True, type=Path)
    parser.add_argument('--compiler', required=True, type=Path, help='MinGW GCC with -m32 support')
    parser.add_argument('--check', action='store_true', help='Verify without changing the generated module')
    parser.add_argument('--evidence', type=Path, help='Optional JSON arithmetic results')
    args = parser.parse_args()
    if hashlib.sha256(args.game.read_bytes()).hexdigest() != GAME_SHA256:
        parser.error('Unsupported executable SHA256; no native code was executed')
    with tempfile.TemporaryDirectory() as temp:
        executable = Path(temp)/'oracle.exe'
        # Reserve game globals before .text so the Windows loader places our
        # process heaps/stacks outside the fixed address range. Adapt the local
        # toolchain's standard script; keep all its CRT/import/TLS sections.
        linker = args.compiler.parent/'ld.exe'
        verbose = subprocess.run([str(linker), '-mi386pe', '--verbose'], check=True,
                                 capture_output=True, text=True, timeout=20).stdout
        script = verbose.split('='*50)[1]
        original = '.text  __image_base__ + ( __section_alignment__ < 0x1000 ? . : __section_alignment__ ) :'
        assert script.count(original) == 1, 'Unsupported linker script'
        script = script.replace(original, '.game __image_base__ + 0x1000 : { *(.game) }\n  .text BLOCK(__section_alignment__) :')
        linker_script = Path(temp)/'oracle.ld'
        linker_script.write_text(script, 'utf8')
        subprocess.run([str(args.compiler), '-m32', '-std=gnu11', '-O2', '-mstackrealign', '-static-libgcc',
                        '-Wl,--image-base,0x3f0000,--disable-dynamicbase,--no-insert-timestamp', '-T', str(linker_script), str(ROOT/'voxel-lighting-oracle.c'),
                        '-o', str(executable)], check=True, timeout=60, creationflags=0x08000000)
        result = subprocess.run([str(executable), str(args.game.resolve())], check=True, capture_output=True,
                                text=True, timeout=20, creationflags=0x08000000)
    record = json.loads(result.stdout)
    generated = module(record)
    target = ROOT/'realmap_voxel_light_tables.py'
    if args.check:
        assert target.read_text('utf8') == generated, 'Native arithmetic differs from the shipped lookup'
    else:
        target.write_text(generated, 'utf8')
    if args.evidence:
        args.evidence.write_text(json.dumps(record, separators=(',', ':')), 'utf8')
    print('PASS: 128 native rows / 11,552 normal-page values; '+('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
